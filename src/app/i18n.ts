const dicts: Record<Locale, Record<string, string>> = { en, fr, ar };

/** Translate a key; falls back to English, then to the key itself. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dicts[getLocale()][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}


/** BCP-47 tag for date formatting in the active locale (Latin digits for Arabic). */
export function dateLocale(): string {
  return { en: 'en-GB', fr: 'fr-FR', ar: 'ar-LB-u-nu-latn' }[getLocale()];
}

export function monthShort(i: number): string {
  return t('common.monthsShort').split('|')[i] ?? '';
}

export function dayShort(i: number): string {
  return t('common.daysShort').split('|')[i] ?? '';
}

